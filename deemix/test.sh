#!/bin/bash

# Правила (для каждой подпапки TARGET; учитываются только её прямые файлы):
#   Папка целиком (скрытые файлы/папки вида .xxx содержимым НЕ считаются):
#     1. Нет вложенных папок И нет аудиофайлов — папка мусор: удаляем её
#        целиком (пустую, только со скрытыми файлами или с любым мусором)
#   Картинки (.jpg/.jpeg/.png):
#     2. В папке есть вложенные папки (папки исполнителей: фото + альбомы) —
#        картинки не трогаем вовсе
#     3. Вложенных папок нет И аудиофайлов меньше 5 — удаляем ВСЕ картинки
#        в папке (включая скрытые). При 5+ аудио картинки остаются.
#
# Корневая папка TARGET не обрабатывается — только её подпапки.
# Обход с -depth (снизу вверх): мусорные вложенные папки удаляются каскадом
# (осиротевшая папка исполнителя без альбомов тоже удалится по правилу 1).
# Содержимое папок читает сам bash (glob, nullglob+dotglob): на каждую папку
# НОЛЬ порождаемых процессов — из внешних процессов остаются только сами rm.

set -o pipefail
shopt -s nullglob dotglob

TARGET="/media/MUSIC"   # тестовый путь; для боевого запуска верни /media/MUSIC

# >>>>>>>>>>>>>>>>>>>>>>>>>>>>>> ОТЛАДКА: ЛОГ УДАЛЕНИЙ >>>>>>>>>>>>>>>>>>>>>>>>>>
# Перехватывает rm и пишет каждый удалённый путь в лог. Для папки, удаляемой
# целиком, сперва логируются все её файлы (включая скрытые), затем сама папка;
# если папка пуста — только строка папки. Скрытые ПОДпапки внутри пишутся
# одной строкой, без перечисления их содержимого.
# ЧТОБЫ ОТКЛЮЧИТЬ ЛОГ — удали весь блок от ОТЛАДКА до КОНЕЦ ОТЛАДКИ.
# Остальной код от лога не зависит: если лог невозможен, удаления выполняются.
#
# Папка для лога выбирается первая, в которую УДАЁТСЯ реально записать файл
# (проверка настоящей записью, т.к. root проходит тест -w даже на read-only):
#   /homeassistant                     — папка конфигурации (терминал/хост HAOS)
#   /config                            — ТА ЖЕ папка конфигурации, но так она
#                                        видна внутри automations (shell_command)
#   /mnt/data/supervisor/homeassistant — та же папка с точки зрения хоста
#   /tmp                               — запасной вариант (виден только в том
#                                        контексте, где запускался скрипт)
# Итоговый removed_files.log виден в File editor и в Samba-шаре «config».
LOG_FILE=""
for _d in /homeassistant /config /mnt/data/supervisor/homeassistant /tmp; do
    [[ -d $_d ]] || continue
    if ( : >> "$_d/.removed_files_write_test" ) 2>/dev/null; then
        LOG_FILE="$_d/media_library_removed_files.log"
        command rm -f -- "$_d/.removed_files_write_test"
        break
    fi
done
if [[ -n $LOG_FILE ]]; then
    echo "ОТЛАДКА: лог удалений пишется в $LOG_FILE" >&2
else
    echo "ОТЛАДКА: не нашлось папки для лога — логирование отключено, удаления продолжатся" >&2
fi
_logline() {
    printf '%s | %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$1" >> "$LOG_FILE"
}
rm() {
    local arg sub
    for arg in "$@"; do
        case "$arg" in -*) continue ;; esac
        if [[ -d $arg ]]; then
            for sub in "$arg"/*; do      # содержимое удаляемой папки (dotglob)
                _logline "$sub"
            done
        fi
        _logline "$arg"
    done
    command rm "$@"
}
[[ -n $LOG_FILE ]] && _logline "=== ЗАПУСК, TARGET=$TARGET ==="
# <<<<<<<<<<<<<<<<<<<<<<<<<<<< КОНЕЦ ОТЛАДКИ: ЛОГ УДАЛЕНИЙ <<<<<<<<<<<<<<<<<<<<<<

# -mindepth 1 — пропустить саму TARGET, брать только подпапки и глубже
# -depth       — сначала самые глубокие папки (для каскадного удаления)
find "$TARGET" -mindepth 1 -depth -type d -print0 | while IFS= read -r -d '' dir; do

    naudio=0        # аудиофайлы прямо в этой папке (скрытые не считаются)
    has_subdir=0    # есть ли вложенные папки (скрытые и симлинки не считаются)
    images=()       # картинки в папке, включая скрытые

    # Один glob вместо двух find на папку: ноль fork+exec
    for f in "$dir"/*; do
        base=${f##*/}
        hidden=0
        case "$base" in .*) hidden=1 ;; esac
        [[ -L $f ]] && continue                     # симлинки не учитываем
        if [[ -d $f ]]; then
            [ "$hidden" -eq 0 ] && has_subdir=1
        elif [[ -f $f ]]; then
            [[ "$base" == *.* ]] || continue        # файл без расширения
            ext=${base##*.}
            case "${ext,,}" in
                # аудио — добавляй новые расширения здесь через |
                mp3|flac|wav|m4a|m4b|aac|ogg|oga|opus|wma|ape|wv|wvc|aif|aiff|dsf|dff|mpc)
                    [ "$hidden" -eq 0 ] && naudio=$((naudio + 1)) ;;
                jpg|jpeg|png) images+=("$f") ;;
            esac
        fi
    done

    # Правило 1: нет вложенных папок и нет аудио — удаляем папку целиком
    if [ "$has_subdir" -eq 0 ] && [ "$naudio" -eq 0 ]; then
        rm -rf -- "$dir"
        continue
    fi

    # Правила 2-3: картинки трогаем только в папках-«листьях» без вложенных папок
    if [ "$has_subdir" -eq 0 ] && [ "$naudio" -lt 5 ] && [ "${#images[@]}" -gt 0 ]; then
        rm -f -- "${images[@]}"
    fi
done
